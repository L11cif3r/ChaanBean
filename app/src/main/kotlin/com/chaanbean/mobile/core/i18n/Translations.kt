/**
 * Ported from main's src/lib/i18n/translations.ts.
 *
 * main's LanguageCode union declares seven codes (en, hi, ml, ta, te, kn, tu) but
 * its TRANSLATIONS record only implements four. We mirror the four that exist
 * rather than inventing the three that do not.
 */
enum class Language(val code: String, val label: String) {
    EN("en", "English"),
    HI("hi", "हिन्दी"),
    ML("ml", "മലയാളം"),
    TA("ta", "தமிழ்");

    companion object {
        fun from(code: String?): Language =
            entries.firstOrNull { it.code == code?.lowercase() } ?: EN
    }
}

